export type Copy = { [Key in keyof (typeof copy)["en"]]: string };

export async function getLocale(): Promise<Locale> {
    const jar = await cookies();
    return jar.get("locale")?.value === "ar" ? "ar" : "en";
}

export function messages(locale: Locale): Copy {
    return copy[locale]; // we are using bracket notation to access the corresponding object in the copy object. if locale is "ar", we return the ar object, otherwise we return the en object.
}
